-- Backup + restructure sst_invoice_hdr / sst_invoice_dtl to match Customer Bill.
-- Detail charge order: Freight, Handling, Fuel Surcharge, Factory Charge, ODA,
-- FOV, Stationery, Taxable, CGST, SGST, IGST, Total.
-- Run after taking file dumps (see backend/backups/).

BEGIN;

-- ---------- DB-side data copies (keep even after swap) ----------
DROP TABLE IF EXISTS sss.sst_invoice_hdr_bak_20261026;
DROP TABLE IF EXISTS sss.sst_invoice_dtl_bak_20261026;
CREATE TABLE sss.sst_invoice_hdr_bak_20261026 AS TABLE sss.sst_invoice_hdr;
CREATE TABLE sss.sst_invoice_dtl_bak_20261026 AS TABLE sss.sst_invoice_dtl;

-- ---------- HEADER ----------
CREATE TABLE sss.sst_invoice_hdr_new (
  record_id       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  company_code    VARCHAR(20),
  tenant_id       INTEGER,
  division_code   VARCHAR(20) NOT NULL,
  loc_code        VARCHAR(4) NOT NULL,
  invoice_no      NUMERIC(10,0) NOT NULL,
  invoice_date    DATE NOT NULL,
  invoice_type    VARCHAR(10) NOT NULL,
  bp_code         NUMERIC(5,0) NOT NULL,
  bp_name         VARCHAR(200),
  loc_gstin       VARCHAR(15),
  bp_gstin        VARCHAR(15),
  sac_code        VARCHAR(10),
  total_inv_amt   NUMERIC(12,2),
  irn_status      VARCHAR(10),
  irn_ackno       NUMERIC(16,0),
  irn_ackdt       TIMESTAMP,
  irn_no          VARCHAR(65),
  irn_qrcode      TEXT,
  write_off_flag  VARCHAR(3),
  write_off_date  DATE,
  inv_sub_date    DATE,
  cancel_flag     VARCHAR(2),
  created_by      VARCHAR(30),
  created_on      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  modified_by     VARCHAR(30),
  modified_on     TIMESTAMP,
  CONSTRAINT sst_invoice_hdr_pk_new PRIMARY KEY (invoice_no, invoice_date, loc_code),
  CONSTRAINT chk_sst_invoice_hdr_invoice_date_not_future
    CHECK (invoice_date IS NULL OR invoice_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_hdr_inv_sub_date_not_future
    CHECK (inv_sub_date IS NULL OR inv_sub_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_hdr_write_off_date_not_future
    CHECK (write_off_date IS NULL OR write_off_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_hdr_created_on_not_future
    CHECK (created_on IS NULL OR created_on::date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_hdr_modified_on_not_future
    CHECK (modified_on IS NULL OR modified_on::date <= CURRENT_DATE)
);

INSERT INTO sss.sst_invoice_hdr_new (
  record_id, company_code, tenant_id, division_code, loc_code,
  invoice_no, invoice_date, invoice_type, bp_code, bp_name,
  loc_gstin, bp_gstin, sac_code, total_inv_amt,
  irn_status, irn_ackno, irn_ackdt, irn_no, irn_qrcode,
  write_off_flag, write_off_date, inv_sub_date, cancel_flag,
  created_by, created_on, modified_by, modified_on
)
SELECT
  record_id, company_code, tenant_id, division_code, loc_code,
  invoice_no, invoice_date, invoice_type, bp_code, bp_name,
  loc_gstin, bp_gstin, sac_code, total_inv_amt,
  irn_status, irn_ackno, irn_ackdt, irn_no, irn_qrcode,
  write_off_flag, write_off_date, inv_sub_date, cancel_flag,
  created_by, created_on, modified_by, modified_on
FROM sss.sst_invoice_hdr;

-- ---------- DETAIL ----------
CREATE TABLE sss.sst_invoice_dtl_new (
  record_id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  company_code      VARCHAR(20),
  division_code     VARCHAR(20),
  invoice_loc       VARCHAR(10) NOT NULL,
  invoice_no        NUMERIC(10,0) NOT NULL,
  invoice_date      DATE NOT NULL,
  invoice_type      VARCHAR(10),
  inv_sr_no         NUMERIC(10,0) NOT NULL,
  docket_no         VARCHAR(20),
  docket_date       DATE,
  docket_from_loc   VARCHAR(10),
  docket_to_loc     VARCHAR(10),
  docket_from_town  VARCHAR(100),
  docket_to_town    VARCHAR(100),
  consignee         VARCHAR(200),
  docket_actwt      NUMERIC(12,2),
  docket_chrwt      NUMERIC(12,2),
  ref_inv_no        NUMERIC(10,0),
  ref_inv_date      DATE,
  ref_inv_loc       VARCHAR(10),
  freight           NUMERIC(12,2) DEFAULT 0,
  handling          NUMERIC(12,2) DEFAULT 0,
  fuel_surcharge    NUMERIC(12,2) DEFAULT 0,
  factory_charge    NUMERIC(12,2) DEFAULT 0,
  oda_charge        NUMERIC(12,2) DEFAULT 0,
  fov               NUMERIC(12,2) DEFAULT 0,
  stationery        NUMERIC(12,2) DEFAULT 0,
  taxable_amt       NUMERIC(12,2) DEFAULT 0,
  cgst              NUMERIC(12,2) DEFAULT 0,
  sgst              NUMERIC(12,2) DEFAULT 0,
  igst              NUMERIC(12,2) DEFAULT 0,
  total_amt         NUMERIC(12,2) DEFAULT 0,
  delivery_status   VARCHAR(20),
  delivery_date     DATE,
  pod_flag          VARCHAR(10),
  created_by        VARCHAR(30),
  created_on        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  modified_by       VARCHAR(30),
  modified_on       TIMESTAMP,
  CONSTRAINT sst_invoice_dtl_pk_new PRIMARY KEY (invoice_no, invoice_date, invoice_loc, inv_sr_no),
  CONSTRAINT chk_sst_invoice_dtl_invoice_date_not_future
    CHECK (invoice_date IS NULL OR invoice_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_dtl_docket_date_not_future
    CHECK (docket_date IS NULL OR docket_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_dtl_ref_inv_date_not_future
    CHECK (ref_inv_date IS NULL OR ref_inv_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_dtl_delivery_date_not_future
    CHECK (delivery_date IS NULL OR delivery_date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_dtl_created_on_not_future
    CHECK (created_on IS NULL OR created_on::date <= CURRENT_DATE),
  CONSTRAINT chk_sst_invoice_dtl_modified_on_not_future
    CHECK (modified_on IS NULL OR modified_on::date <= CURRENT_DATE)
);

INSERT INTO sss.sst_invoice_dtl_new (
  record_id, company_code, division_code, invoice_loc, invoice_no, invoice_date,
  invoice_type, inv_sr_no, docket_no, docket_date, docket_from_loc, docket_to_loc,
  docket_from_town, docket_to_town, consignee, docket_actwt, docket_chrwt,
  ref_inv_no, ref_inv_date, ref_inv_loc,
  freight, handling, fuel_surcharge, factory_charge, oda_charge, fov, stationery,
  taxable_amt, cgst, sgst, igst, total_amt,
  delivery_status, delivery_date, pod_flag,
  created_by, created_on, modified_by, modified_on
)
SELECT
  record_id, company_code, division_code, invoice_loc, invoice_no, invoice_date,
  invoice_type, inv_sr_no, docket_no, docket_date, docket_from_loc, docket_to_loc,
  docket_from_town, docket_to_town, consignee, docket_actwt, docket_chrwt,
  ref_inv_no, ref_inv_date, ref_inv_loc,
  COALESCE(freight, 0),
  COALESCE(handling, loading, 0),
  COALESCE(fuel_surcharge, unloading, 0),
  COALESCE(factory_charge, detention, 0),
  COALESCE(oda_charge, additional_toll, 0),
  COALESCE(fov, green_tax, 0),
  COALESCE(stationery, other_charges, 0),
  COALESCE(taxable_amt, 0),
  COALESCE(cgst, 0), COALESCE(sgst, 0), COALESCE(igst, 0), COALESCE(total_amt, 0),
  delivery_status, delivery_date, pod_flag,
  created_by, created_on, modified_by, modified_on
FROM sss.sst_invoice_dtl;

DROP TABLE sss.sst_invoice_dtl;
DROP TABLE sss.sst_invoice_hdr;
ALTER TABLE sss.sst_invoice_hdr_new RENAME TO sst_invoice_hdr;
ALTER TABLE sss.sst_invoice_dtl_new RENAME TO sst_invoice_dtl;
ALTER TABLE sss.sst_invoice_hdr RENAME CONSTRAINT sst_invoice_hdr_pk_new TO sst_invoice_hdr_pk;
ALTER TABLE sss.sst_invoice_dtl RENAME CONSTRAINT sst_invoice_dtl_pk_new TO invdtl_pk;

ALTER SEQUENCE sss.sst_invoice_hdr_new_record_id_seq RENAME TO sst_invoice_hdr_record_id_seq;
ALTER SEQUENCE sss.sst_invoice_dtl_new_record_id_seq RENAME TO sst_invoice_dtl_record_id_seq;
SELECT setval('sss.sst_invoice_hdr_record_id_seq', COALESCE((SELECT MAX(record_id) FROM sss.sst_invoice_hdr), 1), true);
SELECT setval('sss.sst_invoice_dtl_record_id_seq', COALESCE((SELECT MAX(record_id) FROM sss.sst_invoice_dtl), 1), true);

COMMIT;
